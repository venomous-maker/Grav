#!/usr/bin/env node
// Regenerates the "API" section of every standard-library page in docs/std/
// from the library sources (signatures and the `//` doc comment above each
// declaration), so the reference lists every public type and member.
//
//   node docs/std/gen-api.js           rewrite the pages
//   node docs/std/gen-api.js --check   exit 1 if a page is out of date
//
// A page is docs/std/<category>/<module>.md for lib/<category>/<module>.grav.
// Only the text between the api:begin / api:end markers is rewritten; the
// hand-written introduction and examples around it are kept.
const fs = require("fs");
const path = require("path");
const g = require("../../editors/lsp/grav-index.js");

const ROOT = path.join(__dirname, "../..");
const BEGIN = "<!-- api:begin (generated by docs/std/gen-api.js from the library source; do not edit) -->";
const END = "<!-- api:end -->";
const KIND_WORD = { 5: "class", 11: "interface", 10: "enum", 23: "struct", 12: "fn" };

const isPublic = (detail) => !/^\s*(private|protected)\b/.test(detail || "");
const hidden = (name) => name.startsWith("__") || name === "destructor";
const clean = (d) => (d || "").replace(/^\s*public\s+/, "").replace(/\s*\{.*$/, "").trim();
const oneLine = (doc) => (doc || "").replace(/\s*\n\s*/g, " ").trim();

function memberLine(m, owner) {
  let sig = clean(m.detail);
  if (m.name === "constructor") sig = "new " + sig;
  const doc = oneLine(m.doc);
  return `- \`${sig}\`${doc ? " — " + doc : ""}`;
}

function render(file) {
  const src = fs.readFileSync(path.join(ROOT, file), "utf8");
  const { symbols } = g.parseFile(src, file);
  const out = [];
  const top = symbols.filter((s) => !s.container && s.kind !== 3 && s.kind !== 13 && KIND_WORD[s.kind] !== undefined);
  const fns = top.filter((s) => s.kind === 12 && isPublic(s.detail) && !hidden(s.name));
  for (const t of top.filter((s) => s.kind !== 12 && isPublic(s.detail) && !hidden(s.name))) {
    out.push(`### ${t.detail.replace(/^\s*public\s+/, "")}`, "");
    if (t.doc) out.push(t.doc.trim(), "");
    const members = (t.members || []).filter((m) => isPublic(m.detail) && !hidden(m.name) && m.kind !== 13);
    const groups = [
      ["Constructors", members.filter((m) => m.name === "constructor")],
      ["Static members", members.filter((m) => m.isStatic && m.name !== "constructor")],
      ["Fields", members.filter((m) => !m.isStatic && m.kind === 8)],
      ["Methods", members.filter((m) => !m.isStatic && m.kind !== 8 && m.name !== "constructor" && m.kind !== 22)],
      ["Values", members.filter((m) => m.kind === 22)],
    ];
    for (const [title, list] of groups) {
      if (!list.length) continue;
      out.push(`**${title}**`, "");
      for (const m of list) out.push(m.kind === 22 ? `- \`${clean(m.detail) || m.name}\`${m.doc ? " — " + oneLine(m.doc) : ""}` : memberLine(m, t));
      out.push("");
    }
  }
  if (fns.length) {
    out.push("### Functions", "");
    for (const f of fns) out.push(memberLine(f));
    out.push("");
  }
  return out.join("\n").trim();
}

let stale = 0;
const check = process.argv.includes("--check");
for (const cat of fs.readdirSync(path.join(ROOT, "lib"))) {
  const dir = path.join(ROOT, "lib", cat);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".grav"))) {
    const page = path.join(__dirname, cat, f.replace(/\.grav$/, ".md"));
    if (!fs.existsSync(page)) { console.error(`missing page: docs/std/${cat}/${path.basename(page)}`); stale++; continue; }
    const text = fs.readFileSync(page, "utf8");
    const a = text.indexOf(BEGIN), b = text.indexOf(END);
    if (a < 0 || b < a) { console.error(`no api markers: ${page}`); stale++; continue; }
    const next = text.slice(0, a + BEGIN.length) + "\n\n" + render(`lib/${cat}/${f}`) + "\n\n" + text.slice(b);
    if (next === text) continue;
    if (check) { console.error(`out of date: docs/std/${cat}/${path.basename(page)}`); stale++; continue; }
    fs.writeFileSync(page, next);
    console.log(`wrote docs/std/${cat}/${path.basename(page)}`);
  }
}
process.exit(stale ? 1 : 0);
